export function openUsagePolicyDialog(returnFocus: HTMLElement | null = null) {
  const policyDialog = document.createElement('dialog')
  policyDialog.className = 'privacy-policy-dialog'
  policyDialog.setAttribute('aria-labelledby', 'privacy-policy-title')
  policyDialog.dir = 'rtl'
  policyDialog.innerHTML = `
    <button class="modal-close privacy-policy-close" type="button" aria-label="إغلاق">
      <svg viewBox="0 0 24 24" aria-hidden="true"><path d="m6 6 12 12M18 6 6 18"/></svg>
    </button>
    <h2 id="privacy-policy-title">سياسة الاستخدام</h2>
    <div class="privacy-policy-tabs" role="tablist" aria-label="سياسة الاستخدام">
      <button id="policy-terms-tab" type="button" role="tab" aria-selected="true" aria-controls="policy-terms-panel">سياسة الخصوصية وشروط الاستخدام</button>
      <button id="policy-disclaimer-tab" type="button" role="tab" aria-selected="false" aria-controls="policy-disclaimer-panel" tabindex="-1">إخلاء مسؤولية المطوّر والأمانة التقنية</button>
    </div>
    <div id="policy-terms-panel" class="privacy-policy-content" role="tabpanel" aria-labelledby="policy-terms-tab">
      <h3>سياسة الخصوصية وشروط الاستخدام</h3>
      <p>توضح هذه السياسة شروط استخدام تطبيق أعمال والمبادئ العامة التي تحكم حماية الخصوصية والتعامل مع البيانات. يُرجى مراجعتها قبل إنشاء حساب أو استخدام التطبيق.</p>
      <p>إن إنشاء حساب أو تسجيل الدخول أو استخدام أي من خدمات التطبيق يُعد إقراراً من المستخدم باطلاعه على هذه الشروط وموافقته عليها، بالقدر الذي يسمح به القانون المعمول به.</p>
      <section>
        <h3>أولاً: الاستخدام المشروع للتطبيق</h3>
        <ol>
          <li>يقتصر استخدام التطبيق على الأغراض المشروعة ووفق الأنظمة واللوائح المعمول بها.</li>
          <li>يلتزم المستخدم باستخدام خدمات التطبيق للأغراض المخصصة لها، وبما لا يسبب ضرراً للغير أو ينتهك حقوقهم.</li>
          <li>يحظر إدخال أو نشر أو تداول أي محتوى احتيالي أو مضلل أو مسيء أو مخالف للقانون.</li>
          <li>يتحمل المستخدم مسؤولية دقة المعلومات والبيانات التي يدخلها أو ينشرها عبر التطبيق ومشروعية استخدامها.</li>
        </ol>
      </section>
      <section>
        <h3>ثانياً: حماية النظام ومنع الاستغلال</h3>
        <ol>
          <li>يحظر استغلال أي ثغرة أمنية أو خطأ برمجي أو خلل تقني للوصول إلى بيانات أو معلومات أو وظائف غير مصرح للمستخدم باستخدامها.</li>
          <li>يحظر تجاوز أنظمة الحماية أو قيود الصلاحيات أو آليات تسجيل الدخول والتحقق من الهوية.</li>
          <li>يحظر الوصول إلى حسابات المستخدمين الآخرين أو الاطلاع على بياناتهم أو تعديلها أو حذفها دون إذن.</li>
          <li>يحظر اعتراض الاتصالات أو التلاعب بالطلبات المرسلة إلى الخوادم أو استخراج البيانات بوسائل غير مصرح بها.</li>
          <li>يحظر استخدام أدوات آلية أو برامج خارجية بما يؤثر سلباً في استقرار التطبيق أو أدائه أو أمنه.</li>
          <li>لا يجوز إجراء اختبارات أمنية أو فحوصات للبنية التقنية للتطبيق دون موافقة مسبقة وصريحة من المطوّر.</li>
        </ol>
      </section>
      <section>
        <h3>ثالثاً: خصوصية المستخدمين والبيانات</h3>
        <ol>
          <li>يلتزم المستخدمون باحترام خصوصية الآخرين، وعدم محاولة الوصول إلى بياناتهم الشخصية أو التجارية دون تفويض.</li>
          <li>يحظر جمع بيانات المستخدمين أو نسخها أو مشاركتها أو استخدامها خارج الأغراض المصرح بها.</li>
          <li>يتحمل كل مستخدم مسؤولية حماية بيانات تسجيل الدخول الخاصة به وعدم مشاركتها مع الغير.</li>
          <li>لا يجوز استخدام معلومات المستخدمين الآخرين أو أسعارهم أو بيانات منتجاتهم دون إذن أصحابها.</li>
          <li>تُعالج البيانات الشخصية وفق هذه السياسة وآليات معالجة البيانات المعتمدة للتطبيق والأنظمة المعمول بها.</li>
        </ol>
      </section>
      <section>
        <h3>رابعاً: الإبلاغ عن الأخطاء والثغرات</h3>
        <p>في حال اكتشاف خطأ برمجي أو ثغرة أمنية أو خلل قد يؤثر في خصوصية البيانات أو سلامة التطبيق، يُرجى من المستخدم الالتزام بما يلي:</p>
        <ul>
          <li>إيقاف أي محاولة لاختبار الخلل أو استغلاله فور اكتشافه.</li>
          <li>عدم محاولة الوصول إلى بيانات الغير أو نسخها أو الاحتفاظ بها.</li>
          <li>عدم نشر تفاصيل الخلل أو مشاركتها بما قد يسهّل استغلاله.</li>
          <li>إبلاغ إدارة التطبيق أو المطوّر بالمعلومات اللازمة لتقييم المشكلة ومعالجتها.</li>
        </ul>
        <p>يسهم الإبلاغ المسؤول عن المشكلات التقنية في دعم جهود تقييمها ومعالجتها.</p>
      </section>
      <section>
        <h3>خامساً: إساءة الاستخدام والمسؤولية</h3>
        <p>يجوز لإدارة التطبيق اتخاذ الإجراء المناسب عند رصد مخالفة لهذه الشروط، بما في ذلك تقييد بعض الوظائف أو تعليق الحساب أو إيقافه، بحسب طبيعة المخالفة وما تسمح به الأنظمة المعمول بها.</p>
        <p>تحتفظ إدارة التطبيق بحق اتخاذ الإجراءات القانونية المناسبة عند الاقتضاء.</p>
        <p>يتحمل المستخدم المسؤولية عن الأضرار الناتجة عن إساءة استخدام التطبيق أو مخالفة هذه الشروط، وفقاً للقانون المعمول به.</p>
      </section>
      <section>
        <h3>سادساً: التعديلات على السياسة</h3>
        <p>يجوز تحديث سياسة الخصوصية وشروط الاستخدام عند الحاجة، بما يواكب تطوير الخدمات أو التغييرات التقنية أو المتطلبات النظامية.</p>
        <p>تُنشر النسخة المحدّثة داخل التطبيق، ويُبيّن فيها تاريخ آخر تحديث.</p>
      </section>
      <section>
        <h3>سابعاً: الالتزام بالشروط</h3>
        <p>يُعد استمرار المستخدم في استخدام التطبيق بعد نشر التعديلات قبولاً بالشروط المحدّثة، في الحدود التي يجيزها القانون.</p>
        <p>وفي حال عدم الموافقة على هذه الشروط، يتعين على المستخدم التوقف عن استخدام التطبيق.</p>
      </section>
      <section>
        <h3>ثامناً: حقوق الملكية الفكرية ومنع إعادة البيع أو التأجير</h3>
        <ol>
          <li>تعود حقوق الملكية الفكرية المتعلقة بالتطبيق، بما في ذلك التصميم والواجهات والبرمجيات والأكواد المصدرية والبنية التقنية والوظائف، إلى مالكها أو أصحاب الحقوق المعنيين.</li>
          <li>لا يجوز إعادة بيع التطبيق أو تأجيره أو إعادة توزيعه أو إتاحته للغير، كلياً أو جزئياً، بمقابل أو دونه، دون موافقة مسبقة وصريحة من المطوّر أو صاحب الحق.</li>
          <li>لا يجوز نسخ التطبيق أو إعادة إنتاجه أو إنشاء أعمال مشتقة منه أو استنساخ تصميمه أو برمجته أو استغلال مكوناته لأغراض تجارية دون موافقة خطية مسبقة من أصحاب الحقوق.</li>
          <li>لا يمنح استخدام التطبيق أو الاشتراك فيه أو امتلاك حساب حقاً في ملكية التطبيق أو أكواده أو تصميمه أو بنيته البرمجية.</li>
          <li>لا يجوز فك التطبيق أو إجراء هندسة عكسية عليه أو استخراج أكواده المصدرية أو إعادة استخدامها، إلا في الحدود التي يسمح بها القانون أو بموافقة صريحة من صاحب الحقوق.</li>
          <li>يحتفظ المطوّر أو أصحاب الحقوق بحق اتخاذ الإجراءات القانونية المناسبة بشأن أي استخدام أو نسخ أو إعادة بيع أو تأجير أو استغلال غير مصرح به للتطبيق.</li>
        </ol>
      </section>
      <section>
        <h3>الالتزام بالخصوصية</h3>
        <p>تؤكد إدارة التطبيق التزامها باحترام خصوصية المستخدمين والتعامل مع بياناتهم بمسؤولية، وفق هذه السياسة والأنظمة المعمول بها.</p>
        <p><strong>إدارة التطبيق</strong></p>
      </section>
      <p class="privacy-policy-updated">آخر تحديث: 28 نوفمبر 2026</p>
    </div>
    <div id="policy-disclaimer-panel" class="privacy-policy-content" role="tabpanel" aria-labelledby="policy-disclaimer-tab" hidden>
      <h3>إيضاح بشأن الخصوصية وصلاحيات المطوّر</h3>
      <p>يبيّن هذا القسم طبيعة الصلاحيات التقنية المرتبطة بإدارة التطبيق وآلية التعامل مع البيانات، تأكيداً على احترام خصوصية المستخدمين.</p>
      <section>
        <h3>أولاً: بيانات المصادقة وصلاحيات الجهاز</h3>
        <ul>
          <li>لا تتيح آلية المصادقة للمطوّر الاطلاع على كلمات مرور المستخدمين بصيغتها الأصلية أو استخدامها.</li>
          <li>لا يطلب التطبيق، ضمن وظائفه الحالية، صلاحية الوصول إلى الصور أو الملفات أو جهات الاتصال أو الرسائل أو البيانات الشخصية المخزنة على الجهاز.</li>
          <li>يقتصر استخدام موارد الجهاز على ما تتطلبه الوظائف التي يختارها المستخدم. وأي صلاحية إضافية تستلزمها ميزة مستقبلية ستُطلب مسبقاً، مع توضيح الغرض منها.</li>
        </ul>
      </section>
      <section>
        <h3>ثانياً: الصلاحيات التقنية للمطوّر</h3>
        <p>قد تتطلب إدارة التطبيق وصيانته صلاحيات تقنية لدى مزوّد الخدمة، وقد تتيح هذه الصلاحيات، بحسب إعدادات النظام والحاجة الفنية، الوصول إلى بعض البيانات المحفوظة.</p>
        <p>يقتصر استخدام هذه الصلاحيات على الأغراض التقنية اللازمة لإدارة التطبيق، ومنها:</p>
        <ul>
          <li>صيانة التطبيق وإصلاح الأخطاء البرمجية.</li>
          <li>تشخيص المشكلات التقنية ومعالجة الأعطال.</li>
          <li>تنفيذ التحديثات والتحسينات اللازمة.</li>
          <li>تقديم الدعم الفني، بالقدر الضروري ووفق الإجراءات المعتمدة.</li>
        </ul>
        <p>ولا تُستخدم هذه الصلاحيات لمتابعة المبيعات أو الأنشطة التجارية، أو للاطلاع على الأسعار، أو لاستغلال بيانات المستخدمين لمصلحة شخصية أو خارج الأغراض التقنية المحددة.</p>
      </section>
      <section>
        <h3>ثالثاً: الالتزام بالأمانة واحترام الخصوصية</h3>
        <p>قال الله سبحانه وتعالى:</p>
        <p class="privacy-policy-quote">﴿وَلَا تَجَسَّسُوا﴾ [الحجرات: 12].</p>
        <p>وقال رسول الله ﷺ:</p>
        <p class="privacy-policy-quote">«ولا تجسسوا، ولا تحسسوا» متفق عليه.</p>
        <p>إن القدرة التقنية على الوصول إلى بعض البيانات لا تُعد بحد ذاتها إذناً بالاطلاع عليها أو استخدامها خارج نطاق الحاجة الفنية والتفويض.</p>
        <p>تُعامل بيانات المستخدمين ومعلومات أنشطتهم التجارية بسرية، ولا تُستخدم إلا للأغراض الموضحة في سياسة الخصوصية وشروط الاستخدام، وبما يتوافق مع القوانين المعمول بها.</p>
        <p>يلتزم المطوّر بالتعامل مع البيانات بمهنية ومسؤولية، واتخاذ التدابير المناسبة للمحافظة على سريتها وحماية حقوق أصحابها.</p>
      </section>
    </div>
  `

  const tabs = Array.from(policyDialog.querySelectorAll<HTMLButtonElement>('[role="tab"]'))
  const panels = Array.from(policyDialog.querySelectorAll<HTMLElement>('[role="tabpanel"]'))
  const activateTab = (tab: HTMLButtonElement, focus = false) => {
    tabs.forEach((item) => {
      const selected = item === tab
      item.setAttribute('aria-selected', String(selected))
      item.tabIndex = selected ? 0 : -1
    })
    panels.forEach((panel) => {
      panel.hidden = panel.id !== tab.getAttribute('aria-controls')
    })
    if (focus) tab.focus()
  }
  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => activateTab(tab))
    tab.addEventListener('keydown', (event) => {
      if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight' && event.key !== 'Home' && event.key !== 'End') return
      event.preventDefault()
      const nextIndex = event.key === 'Home'
        ? 0
        : event.key === 'End'
          ? tabs.length - 1
          : (index + (event.key === 'ArrowLeft' ? 1 : -1) + tabs.length) % tabs.length
      activateTab(tabs[nextIndex], true)
    })
  })

  const closePolicy = () => policyDialog.close()
  policyDialog.querySelector('.privacy-policy-close')!.addEventListener('click', closePolicy)
  policyDialog.addEventListener('click', (event) => {
    if (event.target !== policyDialog) return
    const bounds = policyDialog.getBoundingClientRect()
    if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) {
      closePolicy()
    }
  })
  policyDialog.addEventListener('close', () => {
    policyDialog.remove()
    if (returnFocus?.isConnected) returnFocus.focus()
  }, { once: true })
  document.body.append(policyDialog)
  policyDialog.showModal()
  policyDialog.querySelector<HTMLButtonElement>('.privacy-policy-close')!.focus()
}
